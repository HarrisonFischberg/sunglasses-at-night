// Writes Extension/Resources/content/base.css, the manifest-declared sheet
// Safari injects before first paint (no JS, so it needs no settings read).
// It paints the page root with the default look's dark base, but only while
// the system is dark and the content script hasn't set data-sunglasses-off
// (it does that as soon as settings say off / never / already-dark, or once
// it paints its own sheet). Run by `npm test` / `npm run e2e` via their
// pre-scripts; engine/test/base-css.test.js fails if the committed file drifts.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { antiFlashCss, interimCss, OFF_ATTRIBUTE, READY_ATTRIBUTE } from '../src/early.js';
import { defaultSettings } from '../src/settings.js';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
export const BASE_CSS_PATH = resolve(ROOT, 'Extension/Resources/content/base.css');

// The same rules without the media gate: registered at run time by the
// background (first-paint.js) when dark mode is on whatever the system says.
export const BASE_ON_CSS_PATH = resolve(ROOT, 'Extension/Resources/content/base-on.css');
export function baseOnCss() {
  return baseCss()
    .replace('/* Generated by engine/scripts/base-css.js. Do not edit. */', '/* Generated by engine/scripts/base-css.js. Do not edit. Registered by the background when dark mode is on regardless of the system appearance (first-paint.js). */')
    .replace('@media (prefers-color-scheme: dark){\n', '')
    .replace(/\n}\n$/, '\n');
}

export function baseCss() {
  const rules = antiFlashCss(defaultSettings().look)
    .split('}')
    .filter(Boolean)
    .map((rule) => {
      const [selector, body] = rule.split('{');
      // The attribute lives on <html>, so every rule is scoped from :root.
      const gate = `:root:not([${OFF_ATTRIBUTE}])`;
      const scoped = selector.split(',').map((s) => (s.trim() === ':root' ? gate : `${gate} ${s.trim()}`)).join(',');
      return `  ${scoped}{${body}}`;
    })
    .join('\n');
  // Added apart from the generator above: its selector holds commas inside :not().
  const interim = `  ${interimCss(defaultSettings().look, `:root:not([${OFF_ATTRIBUTE}]):not([${READY_ATTRIBUTE}])`)}`;
  return (
    '/* Generated by engine/scripts/base-css.js. Do not edit. */\n' +
    `@media (prefers-color-scheme: dark){\n${rules}\n${interim}\n}\n`
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(BASE_CSS_PATH, baseCss());
  writeFileSync(BASE_ON_CSS_PATH, baseOnCss());
  console.log(`wrote ${BASE_CSS_PATH} and ${BASE_ON_CSS_PATH}`);
}
